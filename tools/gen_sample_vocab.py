#!/usr/bin/env python3
"""Generate the frozen sample vocabulary used by tests and the CLI demo.

Outputs
-------
* `tests/golden/sample-vocab.txt`  —— 人读的规范产物（可 commit、可 diff）。
* `vocab/sample_vocab_wbtest.mbt`  —— 同一份文本内嵌为 MoonBit 字符串常量，
  让测试**零 IO**、在所有后端上都可跑（测试文件不进发布包）。

这不是"训练"（训练是 V0.3 的事），而是一个**确定性夹具**：
256 个单字节 token + 一组固定的人工合并 + 一个特殊 token。

Recipe
------
1. id 0..255 = 单字节 token，rank 同样为 0..255。
2. 对每个词，从首字符开始逐步"累积"出前缀 token（如 hello ->
   'he' -> 'hel' -> 'hell' -> 'hello'），rank 按加入顺序递增。
   这样编码时 BPE 会逐级合并出整词，正好验证合并逻辑。
3. 追加一个特殊 token。

Usage
-----
    python tools/gen_sample_vocab.py
    python tools/gen_sample_vocab.py --check
"""

from __future__ import annotations

import argparse
import base64
import pathlib
import sys
import unicodedata

ROOT = pathlib.Path(__file__).resolve().parent.parent
TXT_OUT = ROOT / "tests" / "golden" / "sample-vocab.txt"
MBT_OUT = ROOT / "vocab" / "sample_vocab_wbtest.mbt"

WORDS = ["hello", " world", "the", " token", "there", "abc"]
SPECIALS = ["<|endoftext|>"]


def build_entries():
    tokens: list[bytes] = []
    ranks: list[int] = []
    seen: set[bytes] = set()

    for b in range(256):
        tokens.append(bytes([b]))
        ranks.append(b)
        seen.add(bytes([b]))

    for word in WORDS:
        cur = word[0]
        for ch in word[1:]:
            cur = cur + ch
            blob = cur.encode("utf-8")
            if blob not in seen:
                seen.add(blob)
                tokens.append(blob)
                ranks.append(len(tokens) - 1)

    special_entries = []
    for lit in SPECIALS:
        blob = lit.encode("utf-8")
        if blob not in seen:
            seen.add(blob)
            tokens.append(blob)
            ranks.append(len(tokens) - 1)
        special_entries.append((tokens.index(blob), lit))

    return tokens, ranks, special_entries


def build_text() -> str:
    tokens, ranks, specials = build_entries()
    b64 = lambda b: base64.b64encode(b).decode("ascii")
    out = []
    out.append("# tally-vocab v1")
    out.append(f"# unicode {unicodedata.unidata_version}")
    out.append(f"# tokens {len(tokens)}")
    out.append("[specials]")
    for tok_id, lit in sorted(specials):
        out.append(f"{tok_id} {b64(lit.encode('utf-8'))}")
    out.append("[tokens]")
    for i, blob in enumerate(tokens):
        out.append(f"{i} {ranks[i]} {b64(blob)}")
    return "\n".join(out) + "\n"


def build_mbt(text: str) -> str:
    lines = text.split("\n")
    if lines and lines[-1] == "":
        lines = lines[:-1]
    parts = []
    for line in lines:
        esc = line.replace("\\", "\\\\").replace('"', '\\"')
        parts.append(f'  "{esc}\\n"')
    body = " +\n".join(parts)
    return (
        "// Generated by tools/gen_sample_vocab.py -- DO NOT EDIT.\n"
        "//\n"
        "// 确定性测试夹具：256 个单字节 token + 人工合并 + 一个特殊 token。\n"
        "// 白盒测试文件，不进发布包。\n"
        "\n"
        "///|\n"
        "let sample_vocab_text : String =\n"
        f"{body} +\n"
        '  ""\n'
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    text = build_text()
    mbt = build_mbt(text)

    if args.check:
        ok = True
        for path, expected in ((TXT_OUT, text), (MBT_OUT, mbt)):
            current = path.read_text(encoding="utf-8") if path.exists() else ""
            if current != expected:
                print(f"{path} is stale", file=sys.stderr)
                ok = False
        return 0 if ok else 1

    TXT_OUT.parent.mkdir(parents=True, exist_ok=True)
    TXT_OUT.write_text(text, encoding="utf-8", newline="\n")
    MBT_OUT.write_text(mbt, encoding="utf-8", newline="\n")
    print(f"wrote {TXT_OUT}")
    print(f"wrote {MBT_OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
