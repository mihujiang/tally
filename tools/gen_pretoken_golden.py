"""生成预切分 golden：用参考实现 cl100k_base 的 pat_str 原文切分穷举语料。

用法：
  python tools/gen_pretoken_golden.py           # 写生成物
  python tools/gen_pretoken_golden.py --check   # 校验生成物与当前一致
"""
import itertools
import re
import sys
from pathlib import Path

import regex
import tiktoken
import tiktoken_ext.openai_public as op

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "bpe" / "pretoken_golden_wbtest.mbt"

ALPHABET = ["a", "1", " ", "\n", "\r", "\t", "!", "\u6211"]
MAXLEN = 3
EXTRA = [
    "", " ", "\n", "\n\n", "\r\n", "a \n ", "a\n \nb", " hello ", "a  ",
    "don't", "DON'T", "we'll", "a\r\n\r\nb", "\u4f60\u597d\u4e16\u754c",
    "9999999", "a!!!\n\n", "x\n\n", "x \n", "a\tb", "\t\n ",
]


def load_pat():
    src = Path(op.__file__).read_text(encoding="utf-8")
    return re.search(r'pat_str": r"""(.*?)"""', src, re.S).group(1)


def cases():
    seen, out = set(), []
    for n in range(MAXLEN + 1):
        for combo in itertools.product(ALPHABET, repeat=n):
            s = "".join(combo)
            if s not in seen:
                seen.add(s)
                out.append(s)
    for s in EXTRA:
        if s not in seen:
            seen.add(s)
            out.append(s)
    return out


def esc(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif 32 <= o < 127:
            out.append(ch)
        else:
            out.append("\\u{%X}" % o)
    return "".join(out)


def render():
    pat = load_pat()
    rx = regex.compile(pat)
    lines = [
        "// Generated by tools/gen_pretoken_golden.py -- DO NOT EDIT.",
        "//",
        "// 参考实现：tiktoken %s / cl100k_base 的 pat_str 原文。" % tiktoken.__version__,
        "// 语料全为合法 UTF-8，片按转义后的文本表示。",
        "//",
        "///|",
        "let pretoken_golden : Array[(String, Array[String])] = [",
    ]
    for s in cases():
        pieces = rx.findall(s)
        texts = ", ".join('"%s"' % esc(p) for p in pieces)
        lines.append('  ("%s", [%s]),' % (esc(s), texts))
    lines.append("]")
    return "\n".join(lines) + "\n"


def main():
    want = render()
    if "--check" in sys.argv:
        cur = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if cur.replace("\r\n", "\n") == want:
            print("gen_pretoken_golden: OK (no drift)")
            return 0
        print("gen_pretoken_golden: DRIFT - regenerate with the tool")
        return 1
    OUT.write_text(want, encoding="utf-8", newline="\n")
    print("gen_pretoken_golden: wrote %s (%d bytes)" % (OUT.name, len(want)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
